#!/bin/bash

# ╔════════════════════════════════════════════════════════════════╗
# ║           سكربت تثبيت منصة صوت الموظف                         ║
# ╚════════════════════════════════════════════════════════════════╝

set -e

echo ""
echo "╔════════════════════════════════════════════════════════════════╗"
echo "║           مرحباً بك في تثبيت منصة صوت الموظف                  ║"
echo "╚════════════════════════════════════════════════════════════════╝"
echo ""

# التحقق من Node.js
if ! command -v node &> /dev/null; then
    echo "❌ Node.js غير مثبت!"
    echo "   يرجى تثبيت Node.js 18 أو أحدث من: https://nodejs.org"
    exit 1
fi

NODE_VERSION=$(node -v | cut -d'v' -f2 | cut -d'.' -f1)
if [ "$NODE_VERSION" -lt 18 ]; then
    echo "❌ إصدار Node.js قديم: $(node -v)"
    echo "   يرجى الترقية لـ Node.js 18 أو أحدث"
    exit 1
fi

echo "✅ Node.js $(node -v) موجود"

# الانتقال لمجلد الخادم
cd server

# تثبيت المكتبات
echo ""
echo "📦 جاري تثبيت المكتبات..."
npm install --production

# إعداد ملف البيئة
if [ ! -f .env ]; then
    echo ""
    echo "⚙️  إنشاء ملف الإعدادات..."
    cp .env.production .env
    echo ""
    echo "╔════════════════════════════════════════════════════════════════╗"
    echo "║  ⚠️  مهم جداً: عدّل ملف server/.env قبل المتابعة!            ║"
    echo "║                                                                ║"
    echo "║  غيّر على الأقل:                                              ║"
    echo "║  - JWT_SECRET (مفتاح سري عشوائي)                              ║"
    echo "║  - DEFAULT_ADMIN_PASSWORD (كلمة مرور المسؤول)                 ║"
    echo "╚════════════════════════════════════════════════════════════════╝"
    echo ""
    read -p "اضغط Enter بعد تعديل الملف للمتابعة..."
fi

# إنشاء المجلدات المطلوبة
mkdir -p data uploads

# تهيئة قاعدة البيانات
echo ""
echo "🗄️  جاري تهيئة قاعدة البيانات..."
npm run init-db

echo ""
echo "╔════════════════════════════════════════════════════════════════╗"
echo "║                    ✅ اكتمل التثبيت بنجاح!                     ║"
echo "╠════════════════════════════════════════════════════════════════╣"
echo "║                                                                ║"
echo "║  لتشغيل التطبيق:                                              ║"
echo "║  cd server && npm start                                        ║"
echo "║                                                                ║"
echo "║  التطبيق سيعمل على: http://localhost:3000                     ║"
echo "║                                                                ║"
echo "╚════════════════════════════════════════════════════════════════╝"
echo ""
